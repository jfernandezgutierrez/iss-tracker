import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const baseURL = process.env.GAMES_TEST_URL || 'http://localhost:3102'
await mkdir('.cache', { recursive: true })
const browser = await chromium.launch({ headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const errors = []
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, serviceWorkers: 'block' })
  const page = await context.newPage()
  page.on('pageerror', error => errors.push(error.message))
  const requests = []
  page.on('request', request => requests.push(request.url()))
  await page.goto(`${baseURL}/juegos`)
  await page.getByRole('heading', { name: 'Juegos espaciales', exact: true }).waitFor()
  assert.equal(await page.getByRole('navigation', { name: 'Navegación principal' }).count(), 0)
  assert.equal(requests.some(url => /phaser|astronaut\.png|monetag|pagead2/.test(url)), false)
  const opener = page.getByRole('button', { name: 'Consultar ISS Runner', exact: true })
  await opener.click()
  const dialog = page.getByRole('dialog')
  await dialog.waitFor()
  await dialog.getByRole('heading', { name: 'Controles para móvil' }).waitFor()
  await page.keyboard.press('Escape')
  await page.waitForFunction(() => !document.querySelector('dialog').open)
  assert.equal(await opener.evaluate(element => element === document.activeElement), true)
  await opener.click()
  await dialog.getByRole('link', { name: 'Jugar', exact: true }).click()
  await page.waitForURL('**/juegos/iss-runner')
  await page.getByRole('button', { name: 'Comenzar partida', exact: true }).waitFor()
  assert.equal(requests.some(url => /astronaut\.png/.test(url)), false)
  await page.screenshot({ path: '.cache/runner-desktop-start.png', fullPage: true })
  await page.getByRole('button', { name: 'Comenzar partida', exact: true }).click()
  await page.getByRole('button', { name: 'Pausar', exact: true }).waitFor()
  await page.locator('canvas').waitFor()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Reanudar', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Reanudar', exact: true }).click()
  await page.keyboard.down('ArrowRight')
  await page.getByRole('heading', { name: 'Fin de la misión', exact: true }).waitFor({ timeout: 12000 })
  await page.keyboard.up('ArrowRight')
  await page.getByText('Partida de invitado: resultado local, sin guardado en la nube.').waitFor()
  await page.screenshot({ path: '.cache/runner-desktop-result.png', fullPage: true })
  await page.getByRole('button', { name: 'Volver a jugar', exact: true }).click()
  await page.getByRole('button', { name: 'Pausar', exact: true }).waitFor()
  await page.screenshot({ path: '.cache/runner-desktop-playing.png' })
  await page.getByRole('link', { name: '← Volver al catálogo de juegos', exact: true }).click()
  assert.equal(await page.locator('canvas').count(), 0)
  await page.getByRole('link', { name: '← Volver a ISS Tracker', exact: true }).click()
  await page.getByRole('navigation', { name: 'Navegación principal' }).waitFor()
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, serviceWorkers: 'block' })
  const mobilePage = await mobile.newPage()
  mobilePage.on('pageerror', error => errors.push(error.message))
  await mobilePage.goto(`${baseURL}/juegos`)
  await mobilePage.getByRole('button', { name: 'Consultar ISS Runner', exact: true }).tap()
  await mobilePage.getByRole('dialog').getByRole('link', { name: 'Jugar', exact: true }).tap()
  await mobilePage.getByRole('button', { name: 'Comenzar partida', exact: true }).tap()
  await mobilePage.getByRole('button', { name: 'Pausar', exact: true }).waitFor()
  assert.equal(await mobilePage.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  const right = mobilePage.getByRole('button', { name: 'Derecha →', exact: true })
  const touchBox = await right.boundingBox()
  const mobileCDP = await mobile.newCDPSession(mobilePage)
  await mobileCDP.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: touchBox.x + touchBox.width / 2, y: touchBox.y + touchBox.height / 2 }] })
  await mobilePage.waitForTimeout(200)
  await mobileCDP.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await mobilePage.getByRole('button', { name: 'Pausar', exact: true }).tap()
  await mobilePage.getByRole('button', { name: 'Reanudar', exact: true }).waitFor()
  await mobilePage.screenshot({ path: '.cache/runner-mobile.png', fullPage: true })
  await mobilePage.goto(`${baseURL}/juegos/cuenta`)
  await mobilePage.getByRole('button', { name: 'Registrarse', exact: true }).tap()
  await mobilePage.getByLabel('Nombre público de jugador').waitFor()
  await mobilePage.getByRole('button', { name: 'Recuperar contraseña', exact: true }).tap()
  await mobilePage.getByRole('button', { name: 'Enviar enlace', exact: true }).waitFor()
  if (process.env.GAMES_TEST_ACCOUNTS) {
    const fixture = JSON.parse((await readFile(process.env.GAMES_TEST_ACCOUNTS, 'utf8')).replace(/^\uFEFF/, ''))
    await mobilePage.getByRole('button', { name: 'Iniciar sesión', exact: true }).tap()
    await mobilePage.getByLabel('Correo electrónico').fill(fixture.emailB)
    await mobilePage.getByLabel('Contraseña', { exact: true }).fill(fixture.password)
    await mobilePage.getByRole('button', { name: 'Entrar', exact: true }).tap()
    await mobilePage.getByRole('heading', { name: 'Tu perfil', exact: true }).waitFor()
    await mobilePage.reload()
    await mobilePage.getByRole('heading', { name: 'Tu perfil', exact: true }).waitFor()
    await mobilePage.getByRole('button', { name: 'Cerrar sesión', exact: true }).tap()
    await mobilePage.getByRole('heading', { name: 'Cuenta de jugador', exact: true }).waitFor()
  }
  assert.deepEqual(errors, [])
  console.log('Browser checks passed: desktop/mobile, dialog focus, guest play, pause, results, cleanup, account forms, lazy loading and no live ads.')
} finally { await browser.close() }
